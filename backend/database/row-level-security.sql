-- School ERP — tenant isolation with SQL Server Row-Level Security (generated from schema.sql)
-- Run after schema.sql. Every query only sees and writes rows of the organization in SESSION_CONTEXT,
-- even if application code forgets a WHERE clause.
--
-- Protected: 77 tables.
-- Not tenant data (global / platform-only, accessed only by the platform service): Plan, Permission, RefreshToken,
-- PasswordResetToken, PaymentWebhookEvent, DemoLead, SchemaMigration.
--
-- The API (src/db/prisma.ts) runs each request in a transaction that first sets the context and
-- clears it again at the end, because pooled connections are reused by other organizations
-- (so @read_only cannot be used):
--   EXEC sp_set_session_context @key = N'organization_id', @value = @orgId;
-- Platform staff (our support team, tenant onboarding) and sign-in use:
--   EXEC sp_set_session_context @key = N'is_platform_admin', @value = 1;
-- Branch-level limits (a principal sees only their branch) are enforced in the API layer.

CREATE SCHEMA security;
GO

-- Strict: the row must belong to the current organization.
CREATE FUNCTION security.fn_tenant_access (@organizationId UNIQUEIDENTIFIER)
RETURNS TABLE
WITH SCHEMABINDING
AS
RETURN
  SELECT 1 AS allowed
  WHERE @organizationId = CAST(SESSION_CONTEXT(N'organization_id') AS UNIQUEIDENTIFIER)
     OR CAST(SESSION_CONTEXT(N'is_platform_admin') AS INT) = 1;
GO

-- Read-only access also to shared system rows (organizationId IS NULL), e.g. built-in roles.
CREATE FUNCTION security.fn_tenant_read (@organizationId UNIQUEIDENTIFIER)
RETURNS TABLE
WITH SCHEMABINDING
AS
RETURN
  SELECT 1 AS allowed
  WHERE @organizationId IS NULL
     OR @organizationId = CAST(SESSION_CONTEXT(N'organization_id') AS UNIQUEIDENTIFIER)
     OR CAST(SESSION_CONTEXT(N'is_platform_admin') AS INT) = 1;
GO

